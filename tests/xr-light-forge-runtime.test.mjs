import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createWorkshop} from '../src/xr/workshopRuntime.js';
import {defaultMotion} from '../src/xr/motionForge.js';
const store=()=>{const m=new Map();return {getItem:k=>m.get(k)??null,setItem:(k,v)=>m.set(k,v)};};
const frame={energy:.4,bass:.9,mid:.15,high:0,beat:.5};
test('live Three.js sculpture gets bounded emissive accent only while audio preview runs',()=>{
 const ws=createWorkshop({scene:new THREE.Scene(),storage:store()});
 ws.add('torus','#2266cc',[0,1.5,-2]);
 ws.setSelectedMotion({...defaultMotion(),mode:'pulse',band:'bass'});
 const id=ws.selected.id,mesh=ws.meshes.get(id),saved=ws.exportJson(),baseColor=mesh.material.color.getHexString();
 ws.setLightSettings({enabled:true,palette:'outrun',gain:1.3});
 assert.equal(mesh.material.emissiveIntensity,0);
 assert.equal(ws.lightSettings.enabled,true);
 ws.toggleMotion();
 ws.tickMotion(.1,frame);
 assert.ok(mesh.material.emissiveIntensity>0&&mesh.material.emissiveIntensity<=1.35);
 assert.equal(mesh.material.emissive.getHexString(),'ff5980');
 assert.equal(ws.exportJson(),saved);
 assert.equal(mesh.material.color.getHexString(),baseColor);
 ws.stopMotion();
 assert.equal(mesh.material.emissiveIntensity,0);
 assert.equal(mesh.material.emissive.getHexString(),'000000');
 assert.equal(ws.exportJson(),saved);
});
test('live palette switching changes emissive only and enabling/disabling does not add undo entries',()=>{
 const ws=createWorkshop({scene:new THREE.Scene(),storage:store()});
 ws.add('box','#449988',[0,1.5,-2]);
 ws.setSelectedMotion({...defaultMotion(),mode:'bob',band:'mid'});
 const id=ws.selected.id,saved=ws.exportJson();
 ws.setLightSettings({enabled:true,palette:'aurora',gain:.7});
 ws.toggleMotion();ws.tickMotion(.1,{...frame,mid:.8});
 const original=ws.meshes.get(id).material.emissive.getHexString();
 ws.setLightSettings({enabled:true,palette:'ember',gain:.8});
 assert.notEqual(ws.meshes.get(id).material.emissive.getHexString(),original);
 assert.equal(ws.lightSettings.palette,'ember');
 assert.equal(ws.exportJson(),saved);
 ws.setLightSettings({enabled:false,palette:'ember',gain:.8});
 assert.equal(ws.meshes.get(id).material.emissiveIntensity,0);
 ws.undo();
 assert.equal(ws.selected.motion,null);
});
test('legacy workshop remains fully importable without local light preferences',()=>{
 const a=createWorkshop({scene:new THREE.Scene(),storage:store()});
 a.add('sphere','#ffcc00',[0,1.5,-2]);
 a.setLightSettings({enabled:true,palette:'ice',gain:1.3});
 const clean=a.exportJson();
 const b=createWorkshop({scene:new THREE.Scene(),storage:store()});
 b.importJson(clean);
 assert.deepEqual(b.lightSettings,{enabled:false,palette:'outrun',gain:.7});
 assert.equal(b.exportJson(),clean);
});
